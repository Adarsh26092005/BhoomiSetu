// Helper utilities
export function getAllStatesAndUTs(): StateOrUtItem[] {
  return [...INDIA_ADMINISTRATIVE_DATA].sort((a, b) => a.name.localeCompare(b.name));
}

export function getStateOrUTByName(name: string): StateOrUtItem | undefined {
  if (!name) return undefined;
  const normalized = name.trim().toLowerCase();
  return INDIA_ADMINISTRATIVE_DATA.find(
    (item) => item.name.toLowerCase() === normalized || item.code.toLowerCase() === normalized,
  );
}

export function getDistrictsByStateName(stateName: string): DistrictItem[] {
  const stateOrUt = getStateOrUTByName(stateName);
  if (!stateOrUt) return [];
  return [...stateOrUt.districts].sort((a, b) => a.name.localeCompare(b.name));
}

export function isValidDistrictForState(stateName: string, districtName: string): boolean {
  if (!stateName || !districtName) return false;
  const districts = getDistrictsByStateName(stateName);
  const normalizedDist = districtName.trim().toLowerCase();
  return districts.some(
    (d) => d.name.toLowerCase() === normalizedDist || d.code.toLowerCase() === normalizedDist,
  );
}
